class Java_loops {
    public static void main(String[] args) {
        // for loop
        for(int i=10;i>1;i--){
            System.out.println("the value of i is:"+i);
        }
        // using while loop
        int j=0;
        while(j<11){
            System.out.println("the value of j is:"+j);
            j++;
        }
    }
}